"""Frozen context sidecars used by the daily report and live pre-match push.

These files are generated by ``scripts/build_context_sidecars.py`` from the
already-frozen training inputs.  The daily inference path only loads them; it
does not retrain or mutate models.
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from datetime import datetime, timezone
from typing import Any

from .entities import canonical_team

# Runtime images install this package under site-packages while mounting frozen
# artifacts at ``/app/artifacts``.  Resolve from the process working directory
# (``/app`` in production) instead of from the installed module location.
ARTIFACT_DIR = (Path.cwd() / "artifacts").resolve()


@lru_cache(maxsize=1)
def load_player_names() -> dict[str, str]:
    path = ARTIFACT_DIR / "player_names.json"
    if not path.exists():
        return {}
    return {str(key): str(value) for key, value in json.loads(path.read_text(encoding="utf-8")).items()}


@lru_cache(maxsize=1)
def load_recent_form() -> dict[str, dict[str, dict[str, int]]]:
    path = ARTIFACT_DIR / "recent_form.json"
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def recent_form_artifact_generated_at() -> str | None:
    path = ARTIFACT_DIR / "recent_form.json"
    return datetime.fromtimestamp(path.stat().st_mtime, timezone.utc).isoformat() if path.exists() else None


def recent_form_artifact_health(max_age_seconds: int = 72 * 3600) -> dict[str, Any]:
    """Report frozen artifact health independently from the latest refresh.

    A provider outage may degrade refresh availability, but it must not turn a
    still-usable last-known-good artifact into an application ERROR.
    """
    path = ARTIFACT_DIR / "recent_form.json"
    status_path = ARTIFACT_DIR / "recent_form_refresh_status.json"
    result: dict[str, Any] = {
        "artifact_status": "ERROR", "generated_at": None, "age_seconds": None,
        "record_count": 0, "team_count": 0, "coverage": 0.0,
        "latest_match_time": None, "refresh_status": "UNKNOWN",
        "last_attempt": None, "last_success": None,
        "last_error_category": None, "provider": None,
    }
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
        cs2 = payload.get("cs2") if isinstance(payload, dict) else None
        metadata = (payload.get("_metadata") or {}).get("cs2") or {}
        if not isinstance(cs2, dict) or not cs2:
            return result
        generated_text = metadata.get("generated_at") or (payload.get("_metadata") or {}).get("generated_at")
        generated = (datetime.fromisoformat(str(generated_text).replace("Z", "+00:00"))
                     if generated_text else datetime.fromtimestamp(path.stat().st_mtime, timezone.utc))
        generated = generated.replace(tzinfo=generated.tzinfo or timezone.utc)
        age = max(0, int((datetime.now(timezone.utc) - generated).total_seconds()))
        result.update({
            "artifact_status": "STALE" if age > max_age_seconds else "OK",
            "generated_at": generated.isoformat(), "age_seconds": age,
            "record_count": int(metadata.get("record_count") or 0),
            "team_count": len(cs2), "coverage": metadata.get("coverage"),
            "latest_match_time": metadata.get("latest_match_time"),
            "provider": metadata.get("provider"),
        })
    except (OSError, json.JSONDecodeError, TypeError, ValueError):
        return result
    if status_path.exists():
        try:
            refresh = json.loads(status_path.read_text(encoding="utf-8"))
            result.update({
                "refresh_status": str(refresh.get("status") or "UNKNOWN"),
                "last_attempt": refresh.get("attempted_at"),
                "last_success": refresh.get("last_success"),
                "last_error_category": refresh.get("error_category"),
                "provider": refresh.get("provider") or result["provider"],
            })
        except (OSError, json.JSONDecodeError, TypeError):
            result.update({"refresh_status": "ERROR", "last_error_category": "STATUS_INVALID"})
    return result


def lol_roster_health() -> dict[str, Any]:
    """Describe the frozen roster sidecar without promoting it to Evidence.

    The sidecar is historical research context.  Its presence must never imply
    a confirmed lineup, even when a provider labels a roster REGISTERED.
    """
    path = ARTIFACT_DIR / "lol_roster.json"
    if not path.exists():
        return {"status": "UNKNOWN", "confidence": "HISTORICAL", "team_count": 0,
                "confirmed_count": 0, "artifact_generated_at": None,
                "source_latest_match_at": None, "error": "ARTIFACT_MISSING"}
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {"status": "ERROR", "confidence": "HISTORICAL", "team_count": 0,
                "confirmed_count": 0, "artifact_generated_at": None,
                "source_latest_match_at": None, "error": "INVALID_ARTIFACT"}
    teams = payload.get("teams") if isinstance(payload, dict) else None
    metadata = payload.get("_metadata") or {} if isinstance(payload, dict) else {}
    team_count = len(teams) if isinstance(teams, dict) else 0
    generated = metadata.get("generated_at") or datetime.fromtimestamp(
        path.stat().st_mtime, timezone.utc).isoformat()
    latest = metadata.get("source_latest_match_at") or metadata.get("latest_match_at")
    return {
        "status": "OK (HISTORICAL)" if team_count else "ERROR",
        "confidence": "HISTORICAL", "team_count": team_count, "confirmed_count": 0,
        "artifact_generated_at": generated, "source_latest_match_at": latest,
        "error": None if team_count else "EMPTY_ARTIFACT",
    }


def player_display_names(sport: str, roster: tuple[str, ...] | list[str]) -> list[str]:
    """Return human-readable roster names for the push template."""
    if not roster:
        return []
    if sport == "lol":
        names = load_player_names()
        displayed = []
        for index, player in enumerate(roster, 1):
            raw = str(player).strip()
            resolved = str(names.get(raw) or "").strip()
            # Oracle's Elixir IDs are internal join keys, not player names.
            # Never leak an unresolved opaque ID into a user-facing push.
            if resolved and not resolved.casefold().startswith("oe:player:"):
                displayed.append(resolved)
            elif raw and not raw.casefold().startswith("oe:player:"):
                displayed.append(raw)
            else:
                # An opaque ID is never a valid display name.  Returning an
                # incomplete lineup makes the existing lineup gate suppress
                # the analysis until the sidecar is rebuilt from all seasons.
                return []
        return displayed
    return [str(player) for player in roster]


def recent_form_for(sport: str, team: str) -> dict[str, int] | None:
    """Return ``{wins, losses, last_n}`` for a team, or None if unavailable."""
    key = canonical_team(sport, team)
    record = load_recent_form().get(sport, {}).get(key)
    if not record:
        return None
    wins = int(record.get("wins", 0))
    losses = int(record.get("losses", 0))
    last_n = int(record.get("last_n", 10))
    return {"wins": wins, "losses": losses, "last_n": last_n}


def format_lineup_section(sport: str, team_a: str, lineup_a: list[str],
                          team_b: str, lineup_b: list[str]) -> str:
    """Build the lineup block required by the pre-match template."""
    if sport == "lol":
        roles = ("上路", "打野", "中路", "下路", "辅助")
        lines = [f"{team_a}："]
        if len(lineup_a) == 5:
            lines.append("  " + " | ".join(f"{role}：{name}" for role, name in zip(roles, lineup_a)))
        else:
            lines.append("  阵容数据不可用")
        lines.append(f"{team_b}：")
        if len(lineup_b) == 5:
            lines.append("  " + " | ".join(f"{role}：{name}" for role, name in zip(roles, lineup_b)))
        else:
            lines.append("  阵容数据不可用")
    elif sport == "cs2":
        lines = [f"{team_a}：{', '.join(lineup_a) or '阵容数据不可用'}",
                 f"{team_b}：{', '.join(lineup_b) or '阵容数据不可用'}"]
    else:
        lines = [f"{team_a}：{'、'.join(lineup_a) or '阵容数据不可用'}",
                 f"{team_b}：{'、'.join(lineup_b) or '阵容数据不可用'}"]
    return "\n".join(lines)
