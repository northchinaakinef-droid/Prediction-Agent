"""Frozen context sidecars used by the daily report and live pre-match push.

These files are generated by ``scripts/build_context_sidecars.py`` from the
already-frozen training inputs.  The daily inference path only loads them; it
does not retrain or mutate models.
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Any

from .entities import canonical_team

ARTIFACT_DIR = Path(__file__).resolve().parents[2] / "artifacts"


@lru_cache(maxsize=1)
def load_player_names() -> dict[str, str]:
    path = ARTIFACT_DIR / "player_names.json"
    if not path.exists():
        return {}
    return {str(key): str(value) for key, value in json.loads(path.read_text(encoding="utf-8")).items()}


@lru_cache(maxsize=1)
def load_recent_form() -> dict[str, dict[str, dict[str, int]]]:
    path = ARTIFACT_DIR / "recent_form.json"
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def player_display_names(sport: str, roster: tuple[str, ...] | list[str]) -> list[str]:
    """Return human-readable roster names for the push template."""
    if not roster:
        return []
    if sport == "lol":
        names = load_player_names()
        return [names.get(str(player), str(player)) for player in roster]
    return [str(player) for player in roster]


def recent_form_for(sport: str, team: str) -> dict[str, int] | None:
    """Return ``{wins, losses, last_n}`` for a team, or None if unavailable."""
    key = canonical_team(sport, team)
    record = load_recent_form().get(sport, {}).get(key)
    if not record:
        return None
    wins = int(record.get("wins", 0))
    losses = int(record.get("losses", 0))
    last_n = int(record.get("last_n", 10))
    return {"wins": wins, "losses": losses, "last_n": last_n}


def format_lineup_section(sport: str, team_a: str, lineup_a: list[str],
                          team_b: str, lineup_b: list[str]) -> str:
    """Build the lineup block required by the pre-match template."""
    if sport == "lol":
        roles = ("上路", "打野", "中路", "下路", "辅助")
        lines = [f"{team_a}："]
        if len(lineup_a) == 5:
            lines.append("  " + " | ".join(f"{role}：{name}" for role, name in zip(roles, lineup_a)))
        else:
            lines.append("  阵容数据不可用")
        lines.append(f"{team_b}：")
        if len(lineup_b) == 5:
            lines.append("  " + " | ".join(f"{role}：{name}" for role, name in zip(roles, lineup_b)))
        else:
            lines.append("  阵容数据不可用")
    elif sport == "cs2":
        lines = [f"{team_a}：{', '.join(lineup_a) or '阵容数据不可用'}",
                 f"{team_b}：{', '.join(lineup_b) or '阵容数据不可用'}"]
    else:
        lines = [f"{team_a}：{'、'.join(lineup_a) or '阵容数据不可用'}",
                 f"{team_b}：{'、'.join(lineup_b) or '阵容数据不可用'}"]
    return "\n".join(lines)
